// STANDARDS-1 (Rowan, 2026-11-25: "Standards, don't reinvent the wheel. Apply standards."): the atlas speaks published vocabularies instead of a
// home-grown JSON shape, so search engines, data catalogues, research tools and other agents read it with no adapter.
// - schema.org ClaimReview on every programme page: the claim "<programme> improves <outcome>" with the computed verdict as its rating; each trial is
//   a ScholarlyArticle, linked to https://doi.org/<doi> once the citation check (CITE-VERIFIED-1) has resolved it.
// - ISO 3166-1 alpha-2 codes for every country the atlas records (iso3166.js), carried as spatialCoverage.
// - W3C DCAT 3 catalogue of the atlas's datasets and distributions at /api/catalog.
// - W3C PROV-O history of every re-grade at /api/changes.jsonld: each grade is an Entity generated by a re-grading Activity and derived from the
//   grade before it.
// - OpenAPI 3.1 description of the public API at /openapi.json.
// Nothing here is typed by hand: every value comes from programmes.js, the computed grades, the citation table or the grade_changes table.
import { PROGRAMMES, AREAS } from "./programmes.js";
import { VERDICTS, STRENGTHS } from "./grade.js";
import { COUNTRIES } from "./countries.js";
import { ISO3166 } from "./iso3166.js";
import { SITE } from "./promote.js";

const iso = ms => new Date(ms).toISOString();
const PUBLISHER = { "@type": "Organization", name: "What Works", url: SITE, parentOrganization: { "@type": "Organization", name: "Ultrastable", url: "https://ultrastable.io/" } };

// Ratings are the verdict ranks of grade.js (1 backfires .. 5 works); "too little evidence" has no position on that scale, so it carries words only.
export function rating(g) {
  const v = VERDICTS[g.verdict];
  const r = { "@type": "Rating", alternateName: v.name, ratingExplanation: v.say + " " + STRENGTHS[g.strength].name + " evidence." };
  return v.rank > 0 ? { ...r, ratingValue: v.rank, worstRating: 1, bestRating: 5 } : r;
}

export function place(setting) {
  const c = COUNTRIES[setting.id], code = ISO3166[setting.id];
  if (!c || !code) return null;
  return { "@type": "Country", name: c.name, identifier: { "@type": "PropertyValue", propertyID: "ISO 3166-1 alpha-2", value: code } };
}

export function article(t, cite) {
  const a = { "@type": "ScholarlyArticle", name: t.title, author: t.authors, datePublished: String(t.year), isPartOf: { "@type": "Periodical", name: t.venue } };
  if (cite && cite.doi) { a.identifier = { "@type": "PropertyValue", propertyID: "DOI", value: cite.doi }; a.sameAs = "https://doi.org/" + cite.doi; }
  return a;
}

// One programme page: the ClaimReview a fact-checker would publish, computed from the trials.
export function claimReview(p, g, { citations = {}, settings = [], changes = [] } = {}) {
  const url = SITE + "/p/" + p.id;
  const last = changes.length ? Math.max(...changes.map(c => c.at)) : null;
  const where = settings.map(place).filter(Boolean);
  const out = {
    "@context": "https://schema.org", "@type": "ClaimReview", "@id": url + "#review", url,
    claimReviewed: `${p.name} improves ${p.outcome}.`,
    itemReviewed: { "@type": "Claim", name: p.name, description: p.what, appearance: p.trials.map((t, i) => article(t, citations[i])) },
    reviewRating: rating(g), author: PUBLISHER,
    about: { "@type": "DefinedTerm", name: (AREAS.find(a => a.id === p.area) || {}).name, inDefinedTermSet: SITE + "/#areas" }
  };
  if (where.length) out.itemReviewed.spatialCoverage = where;
  if (last) out.dateModified = iso(last);
  return out;
}

// DCAT 3: the atlas as a catalogue of datasets, each with the distributions this Worker serves.
export function catalog(now = Date.now()) {
  const dist = (path, media, title) => ({ "@type": "dcat:Distribution", "dct:title": title, "dcat:accessURL": { "@id": SITE + path }, "dcat:mediaType": media });
  return {
    "@context": { dcat: "http://www.w3.org/ns/dcat#", dct: "http://purl.org/dc/terms/", prov: "http://www.w3.org/ns/prov#", foaf: "http://xmlns.com/foaf/0.1/", schema: "https://schema.org/" },
    "@id": SITE + "/api/catalog", "@type": "dcat:Catalog", "dct:title": "What Works: a living atlas of what works in public policy",
    "dct:publisher": { "@type": "foaf:Organization", "foaf:name": "What Works", "foaf:homepage": { "@id": SITE } }, "dct:modified": iso(now),
    "dcat:dataset": [
      { "@id": SITE + "/#programmes", "@type": "dcat:Dataset", "dct:title": "Programmes and their computed grades",
        "dct:description": `${PROGRAMMES.length} public programmes in ${AREAS.length} areas, each graded by its trials and re-graded as evidence lands.`,
        "dcat:keyword": AREAS.map(a => a.name), "dcat:theme": AREAS.map(a => ({ "@id": SITE + "/area/" + a.id })),
        "prov:wasGeneratedBy": { "@type": "prov:Activity", "dct:description": "Hourly beat: citation check, trial discovery, read-in and re-grade" },
        "dcat:distribution": [dist("/api/programmes", "application/json", "Programmes (JSON)"), dist("/feed.json", "application/feed+json", "Re-grades (JSON Feed)")] },
      { "@id": SITE + "/#changes", "@type": "dcat:Dataset", "dct:title": "Grade history",
        "dct:description": "Every grade change with its reason, as W3C PROV-O.",
        "dcat:distribution": [dist("/api/changes.jsonld", "application/ld+json", "Re-grades (PROV-O JSON-LD)"), dist("/api/changes", "application/json", "Re-grades (JSON)")] },
      { "@id": SITE + "/#graph", "@type": "dcat:Dataset", "dct:title": "Knowledge graph",
        "dct:description": "Programmes, outcomes, countries, studies, authors and venues and the links between them.",
        "dcat:distribution": [dist("/graph.json", "application/json", "Graph (JSON)"), dist("/api/graph", "application/json", "Graph read side (JSON)")] }
    ],
    "dcat:service": { "@type": "dcat:DataService", "dct:title": "What Works API", "dcat:endpointURL": { "@id": SITE + "/api/" }, "dcat:endpointDescription": { "@id": SITE + "/openapi.json" } }
  };
}

// PROV-O: a grade is an Entity; each change is the Activity that generated it, and the new grade was derived from the one before it.
export function provChanges(changes) {
  const ent = (c, v, s, n) => ({ "@id": `${SITE}/p/${c.programme}#grade-${n}`, "@type": "prov:Entity", "schema:name": `${VERDICTS[v] ? VERDICTS[v].name : v} (${s})` });
  const graph = [];
  for (const c of changes) {
    const act = { "@id": `${SITE}/changes#${c.id}`, "@type": "prov:Activity", "prov:endedAtTime": { "@value": iso(c.at), "@type": "xsd:dateTime" },
      "schema:description": c.reason, "schema:additionalType": c.kind, "prov:used": { "@id": `${SITE}/p/${c.programme}` } };
    const to = { ...ent(c, c.to_verdict, c.to_strength, c.id), "prov:wasGeneratedBy": { "@id": act["@id"] }, "prov:generatedAtTime": act["prov:endedAtTime"],
      "prov:specializationOf": { "@id": `${SITE}/p/${c.programme}#grade` } };
    if (c.from_verdict) to["prov:wasDerivedFrom"] = { "@id": `${SITE}/p/${c.programme}#grade-before-${c.id}`, "@type": "prov:Entity", "schema:name": `${VERDICTS[c.from_verdict] ? VERDICTS[c.from_verdict].name : c.from_verdict} (${c.from_strength})` };
    graph.push(act, to);
  }
  return { "@context": { prov: "http://www.w3.org/ns/prov#", schema: "https://schema.org/", xsd: "http://www.w3.org/2001/XMLSchema#" }, "@graph": graph };
}

// OpenAPI 3.1: every public GET route the Worker serves, generated from one table so the description and the router cannot drift (test).
export const ROUTES = [
  ["/api/programmes", "listProgrammes", "Every programme with its computed grade and trials", "application/json"],
  ["/api/programme/{id}", "getProgramme", "One programme with its grade, trials, grade history and unread new evidence", "application/json"],
  ["/api/changes", "listChanges", "The latest grade changes", "application/json"],
  ["/api/changes.jsonld", "listChangesProv", "The latest grade changes as W3C PROV-O", "application/ld+json"],
  ["/api/catalog", "getCatalog", "W3C DCAT catalogue of the atlas's datasets", "application/ld+json"],
  ["/api/metrics", "getMetrics", "The atlas's measures", "application/json"],
  ["/api/freshness", "getFreshness", "Whether every programme was checked inside its cadence (503 when not)", "application/json"],
  ["/api/settings", "getSettings", "Where the evidence comes from, by country and setting", "application/json"],
  ["/api/graph", "getGraph", "Knowledge graph read side (public kinds)", "application/json"],
  ["/feed.json", "getFeed", "Re-grades as a JSON Feed 1.1", "application/feed+json"],
  ["/graph.json", "getGraphSnapshot", "Knowledge graph snapshot", "application/json"],
  ["/health", "getHealth", "Whether the atlas is working, by part (503 when not)", "application/json"]
];
export function openapi() {
  const paths = {};
  for (const [path, operationId, summary, media] of ROUTES) {
    const op = { operationId, summary, responses: { 200: { description: "OK", content: { [media]: {} } } } };
    if (path.includes("{id}")) { op.parameters = [{ name: "id", in: "path", required: true, schema: { type: "string", enum: PROGRAMMES.map(p => p.id) } }]; op.responses[404] = { description: "No programme with that id" }; }
    paths[path] = { get: op };
  }
  return { openapi: "3.1.0", info: { title: "What Works API", version: "1.0.0", description: "A living atlas of what works in public policy. Read-only, no key, CORS open." },
    servers: [{ url: SITE }], paths };
}
